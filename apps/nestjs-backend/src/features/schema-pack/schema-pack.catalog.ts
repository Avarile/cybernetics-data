/** A field as it will exist in a table: declared there, or generated by another table's link. */
export interface ICatalogField {
  table: string;
  key: string;
  name: string;
  type: FieldType;
  /** The declared spec; absent for a symmetric field. */
  spec?: ISchemaPackField;
  /** For a symmetric field: the owning link. */
  symmetricOf?: { table: string; key: string };
  /** Both packs, when the field only exists if both are installed. */
  bridge?: [SchemaPackId, SchemaPackId];
}

export interface ICatalogTable {
  pack: SchemaPackId;
  table: ISchemaPackTable;
  /** Every field the table can hold, in display order. */
  fields: Map<string, ICatalogField>;
}

export interface ISchemaPackCatalog {
  packs: ISchemaPack[];
  bridges: ISchemaPackBridge[];
  seeds: ISchemaPackSeed[];
  tables: Map<string, ICatalogTable>;
}

export interface IRawCatalog {
  packs: unknown[];
  bridges: unknown;
  seeds: unknown[];
}

// eslint-disable-next-line @typescript-eslint/naming-convention
const RAW: IRawCatalog = {
  packs: [progressJson, peopleJson, knowledgeJson, financeJson],
  bridges: bridgesJson,
  seeds: [progressSeedJson, peopleSeedJson, knowledgeSeedJson, financeSeedJson],
};

export const isLinkSpec = (spec: ISchemaPackField) =>
  spec.type === FieldType.Link && !spec.isLookup;

const formulaRefs = (expression: string) =>
  [...expression.matchAll(SCHEMA_PACK_FORMULA_REF)].map((m) => m[1]);

/** Keys of the catalog fields a declared field depends on, as `table.key`. */
export const dependenciesOf = (
  catalog: Pick<ISchemaPackCatalog, 'tables'>,
  tableKey: string,
  spec: ISchemaPackField
): string[] => {
  if (spec.lookup) {
    const link = catalog.tables.get(tableKey)?.fields.get(spec.lookup.link);
    const foreign = link && linkTarget(catalog, link);
    return [`${tableKey}.${spec.lookup.link}`, `${foreign ?? '?'}.${spec.lookup.field}`];
  }
  if (spec.type === FieldType.Formula) {
    return formulaRefs(String(spec.options?.expression ?? '')).map((k) => `${tableKey}.${k}`);
  }
  return [];
};

/** The table a link (or symmetric link) field points at. */
export const linkTarget = (
  catalog: Pick<ISchemaPackCatalog, 'tables'>,
  field: ICatalogField
): string | undefined => {
  if (field.spec?.link) return field.spec.link.table;
  return field.symmetricOf?.table;
};

/**
 * Validates the shipped JSON and cross-checks every reference, so a broken pack fails at boot
 * (and in CI) rather than at a user's first login.
 */
// eslint-disable-next-line sonarjs/cognitive-complexity
export const buildCatalog = (raw: IRawCatalog = RAW): ISchemaPackCatalog => {
  const problems: string[] = [];
  const packs = raw.packs.map((p) => schemaPackSchema.parse(p));
  const bridges = schemaPackBridgeSchema.array().parse(raw.bridges);
  const seeds = raw.seeds.map((s) => schemaPackSeedSchema.parse(s));
  if (packs.map((p) => p.id).join() !== SCHEMA_PACK_IDS.join()) {
    problems.push(`packs must be exactly ${SCHEMA_PACK_IDS.join(', ')} in that order`);
  }

  const tables = new Map<string, ICatalogTable>();
  for (const pack of packs) {
    for (const table of pack.tables) {
      if (tables.has(table.key)) problems.push(`table ${table.key} is declared twice`);
      const primaries = table.fields.filter((f) => f.isPrimary).length;
      if (primaries !== 1) problems.push(`table ${table.key} has ${primaries} primary fields`);
      tables.set(table.key, { pack: pack.id, table, fields: new Map() });
    }
  }

  const add = (field: ICatalogField) => {
    const table = tables.get(field.table);
    if (!table) return problems.push(`field ${field.key} targets unknown table ${field.table}`);
    if (table.fields.has(field.key)) problems.push(`duplicate field ${field.table}.${field.key}`);
    table.fields.set(field.key, field);
  };
  const declare = (
    tableKey: string,
    spec: ISchemaPackField,
    bridge?: [SchemaPackId, SchemaPackId]
  ) => {
    add({ table: tableKey, key: spec.key, name: spec.name, type: spec.type, spec, bridge });
    if (spec.link?.symmetric) {
      add({
        table: spec.link.table,
        key: spec.link.symmetric.key,
        name: spec.link.symmetric.name,
        type: FieldType.Link,
        symmetricOf: { table: tableKey, key: spec.key },
        bridge,
      });
    }
  };
  for (const pack of packs) {
    pack.tables.forEach((t) => t.fields.forEach((f) => declare(t.key, f)));
  }
  for (const bridge of bridges) {
    for (const { table, field } of bridge.fields) {
      const packsOfEnds = [
        tables.get(table)?.pack,
        field.link && tables.get(field.link.table)?.pack,
      ];
      if (!packsOfEnds.every((p) => p && bridge.packs.includes(p))) {
        problems.push(`bridge field ${table}.${field.key} does not join ${bridge.packs.join('+')}`);
      }
      declare(table, field, bridge.packs);
    }
  }

  for (const [tableKey, { fields }] of tables) {
    for (const field of fields.values()) {
      if (!field.spec) continue;
      if (field.spec.link) {
        const foreign = tables.get(field.spec.link.table);
        const shown = field.spec.link.lookupField;
        if (foreign && shown && !foreign.fields.has(shown)) {
          problems.push(`${tableKey}.${field.key} shows unknown ${foreign.table.key}.${shown}`);
        }
      }
      for (const dep of dependenciesOf({ tables }, tableKey, field.spec)) {
        const [t, k] = dep.split('.');
        if (!tables.get(t)?.fields.has(k)) problems.push(`${tableKey}.${field.key} needs ${dep}`);
      }
    }
  }
  problems.push(...checkSeeds(seeds, tables));
  if (problems.length) throw new Error(`Invalid schema packs:\n- ${problems.join('\n- ')}`);
  return { packs, bridges, seeds, tables };
};

const checkSeeds = (seeds: ISchemaPackSeed[], tables: Map<string, ICatalogTable>) => {
  const problems: string[] = [];
  const rowKeys = new Map<string, Set<string>>();
  for (const seed of seeds) {
    for (const { table, rows } of seed.tables) {
      const keys = rowKeys.get(table) ?? new Set<string>();
      rows.forEach((r) => r.key && keys.add(r.key));
      rowKeys.set(table, keys);
    }
  }
  for (const seed of seeds) {
    for (const { table: tableKey, rows } of seed.tables) {
      const table = tables.get(tableKey);
      if (!table || table.pack !== seed.pack) {
        problems.push(`seed table ${tableKey} is not in pack ${seed.pack}`);
        continue;
      }
      rows.forEach((row, i) => {
        const at = `seed ${tableKey}[${i}]`;
        for (const [key, value] of Object.entries(row.fields)) {
          const spec = table.fields.get(key)?.spec;
          if (!spec || isLinkSpec(spec) || spec.lookup || spec.type === FieldType.Formula) {
            problems.push(`${at} writes ${key}, which is not a plain field`);
            continue;
          }
          const choices = spec.options?.choices as { name: string }[] | undefined;
          if (choices && !choices.some((c) => c.name === value)) {
            problems.push(`${at} sets ${key} to "${String(value)}", not one of its choices`);
          }
        }
        for (const [key, targets] of Object.entries(row.links ?? {})) {
          const field = table.fields.get(key);
          const foreign = field && linkTarget({ tables }, field);
          if (!foreign) {
            problems.push(`${at} links through ${key}, which is not a link`);
            continue;
          }
          const missing = targets.filter((t) => !rowKeys.get(foreign)?.has(t));
          if (missing.length)
            problems.push(`${at} links to unknown ${foreign} rows ${missing.join()}`);
        }
      });
    }
  }
  return problems;
};

let cached: ISchemaPackCatalog | undefined;
export const getSchemaPackCatalog = () => (cached ??= buildCatalog());

export const toCatalogVo = (catalog: ISchemaPackCatalog): ISchemaPackCatalogVo => {
  const fieldVo = (f: ICatalogField) => ({
    key: f.key,
    name: f.name,
    type: f.type,
    ...(f.spec?.isLookup ? { isLookup: true } : {}),
    ...(f.type === FieldType.Link && !f.spec?.isLookup ? { linkTo: linkTarget(catalog, f) } : {}),
  });
  return {
    packs: catalog.packs.map((pack) => ({
      id: pack.id,
      version: pack.version,
      tables: pack.tables.map((t) => ({
        key: t.key,
        name: t.name,
        icon: t.icon,
        optional: Boolean(t.optional),
        fields: [...catalog.tables.get(t.key)!.fields.values()]
          .filter((f) => !f.bridge)
          .map(fieldVo),
      })),
    })),
    bridges: catalog.bridges.map((b) => ({
      packs: b.packs,
      fields: [...catalog.tables.values()].flatMap(({ fields }) =>
        [...fields.values()]
          .filter((f) => f.bridge?.join() === b.packs.join())
          .map((f) => ({ table: f.table, field: fieldVo(f) }))
      ),
    })),
    currencies: Object.keys(SCHEMA_PACK_CURRENCIES),
  };
};
